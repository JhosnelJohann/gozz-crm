"use client";
import type { CSSProperties } from "react";

interface IconProps {
  size?: number | string;
  className?: string;
  color?: string;
  style?: CSSProperties;
  onClick?: (e: React.MouseEvent) => void;
  [key: string]: any;
}

function makeIcon(slug: string) {
  function BiIcon({ size, className, color, style, weight, strokeWidth, absoluteStrokeWidth, ...rest }: IconProps) {
    const dim = typeof size === "number" ? `${size}px` : size;
    return (
      <i
        className={`bi bi-${slug}${className ? ` ${className}` : ""}`}
        style={{ fontSize: dim, lineHeight: 1, color, ...style }}
        aria-hidden="true"
        {...rest}
      />
    );
  }
  BiIcon.displayName = `BiIcon(${slug})`;
  return BiIcon;
}

